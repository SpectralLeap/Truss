using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Formatting;

namespace Truss.Results.Extensions.Fluent.SourceGenerator;

[Generator]
public sealed class ExtensionSourceGenerator : ISourceGenerator
{
    public void Initialize(GeneratorInitializationContext context)
    {
        // Not generating
    }

    public void Execute(GeneratorExecutionContext context)
    {
        int maxSize = 7;

        for (var size = 1; size <= maxSize; size++)
        {
            GenerateFile(size, context);
        }
    }

    private void GenerateFile(int size, GeneratorExecutionContext context)
    {
        var thenGenerator = new ThenExtensionGenerator(size);
        var doGenerator = new DoExtensionGenerator(size);
        var andGenerator = new AndExtensionGenerator(size);

        var source = $$"""
                       // <auto-generated/>
                       using System;
                       using System.Threading.Tasks;

                       namespace Truss.Results.Extensions.Fluent;

                       public static class ResultExtensions{{size}}
                       {
                          {{thenGenerator.Generate()}}
                          
                          {{doGenerator.Generate()}}
                          
                          {{andGenerator.Generate()}}
                       }
                       """;

        var formattedCode = Format(source);
        
        context.AddSource($"ResultExtensions{size}.g.cs", formattedCode);
    }

    private string Format(string source)
    {
        var syntaxTree = CSharpSyntaxTree.ParseText(source);
        var formattedRoot = Formatter.Format(syntaxTree.GetRoot(), new AdhocWorkspace());
        return formattedRoot.ToFullString();
    }
}